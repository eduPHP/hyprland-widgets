#!/usr/bin/env bash
# Make hyprlock use hyprlock-theme. Runs as you, no root:
#
#   ./install.sh               back up ~/.config/hypr/hyprlock.conf, point it at the generated look
#   ./install.sh --uninstall   put the backup back and remove the hook
#   ./install.sh --dry-run     print what it would do
#
# What it touches:
#   ~/.config/hypr/hyprlock.conf                      replaced by one `source =` line (backup kept next to it)
#   ~/.config/hypr/hyprlock.conf.before-hyprlock-theme  the backup, made once
#   ~/.local/state/hyprlock-theme/hyprlock.conf       the generated look, rewritten on every theme change
#   ~/.config/omarchy/hooks/theme-set.d/hyprlock-theme, ~/.local/bin/hyprlock-theme   links
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
CONF=$HOME/.config/hypr/hyprlock.conf
BACKUP=$CONF.before-hyprlock-theme
STATE=${XDG_STATE_HOME:-$HOME/.local/state}/hyprlock-theme
HOOK=$HOME/.config/omarchy/hooks/theme-set.d/hyprlock-theme
BIN=$HOME/.local/bin/hyprlock-theme
MARK="# hyprlock-theme"

DRY=0 UNINSTALL=0
while (($#)); do
  case $1 in
    --dry-run) DRY=1 ;;
    --uninstall) UNINSTALL=1 ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done
run() { echo "+ $*"; ((DRY)) || "$@"; }

if ((EUID == 0)); then
  echo "hyprlock-theme: run it as yourself, not root; hyprlock and its config are yours" >&2
  exit 1
fi

if ((UNINSTALL)); then
  if [[ -f $BACKUP ]]; then run mv -f "$BACKUP" "$CONF"
  elif [[ -f $CONF ]] && grep -q "^$MARK" "$CONF"; then run rm -f "$CONF"; fi
  run rm -f "$HOOK" "$BIN"
  run rm -rf "$STATE"
  echo "hyprlock-theme removed; hyprlock uses your old config from the next lock"
  exit 0
fi

command -v hyprlock >/dev/null || { echo "hyprlock-theme: hyprlock isn't installed" >&2; exit 1; }

# 1. back up the current config once (never overwrite an earlier backup with our own one-liner)
if [[ -f $CONF ]] && ! grep -q "^$MARK" "$CONF"; then
  if [[ -e $BACKUP ]]; then
    stamp=$(date +%Y%m%d-%H%M%S)
    run cp -p "$CONF" "$CONF.before-hyprlock-theme.$stamp"
  else
    run cp -p "$CONF" "$BACKUP"
  fi
fi

# 2. generate the look for the current theme
run "$HERE/hyprlock-theme" sync

# 3. point hyprlock at it
if ((DRY)); then
  echo "+ write $CONF: source = $STATE/hyprlock.conf"
else
  mkdir -p "$(dirname "$CONF")"
  printf '%s: generated by hyprland-widgets/hyprlock-theme. Undo with its install.sh --uninstall,\n# which restores %s.\nsource = %s/hyprlock.conf\n' \
    "$MARK" "$(basename "$BACKUP")" "$STATE" > "$CONF"
fi

# 4. follow theme changes, and put the command on PATH
run mkdir -p "$(dirname "$HOOK")" "$(dirname "$BIN")"
run ln -sfn "$HERE/hyprlock-theme" "$HOOK"
run ln -sfn "$HERE/hyprlock-theme" "$BIN"

echo
echo "hyprlock-theme installed. It shows the next time the screen locks; to see it now:"
echo "  hyprlock-theme preview      (locks the screen; unlock with your password)"
