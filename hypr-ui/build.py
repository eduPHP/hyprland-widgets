#!/usr/bin/env python3
"""Render tokens.json into the per-toolkit outputs.

  gtk/hypr-ui.css   GTK4 base stylesheet (from gtk/hypr-ui.css.in)
  qml/Tokens.qml    Quickshell singleton

Run after editing tokens.json or the template; widgets pick the change up on restart
(Quickshell reloads hyprbt by itself).
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
HEADER = "GENERATED by hypr-ui/build.py from tokens.json. Do not edit; change tokens.json and rerun."


def flat(d, prefix=""):
    out = {}
    for k, v in d.items():
        if k.startswith("$"):
            continue
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(flat(v, key + "."))
        else:
            out[key] = v
    return out


def camel(path):
    first, *rest = path.split(".")
    return first + "".join(p[:1].upper() + p[1:] for p in rest)


def gtk(tokens, values):
    colors = "\n".join(f"@define-color {k} {v};" for k, v in tokens["color"].items())
    tpl = (ROOT / "gtk/hypr-ui.css.in").read_text()

    def sub(m):
        key = m.group(1)
        if key == "colors":
            return colors
        if key not in values:
            raise SystemExit(f"gtk/hypr-ui.css.in: unknown token {{{{{key}}}}}")
        return str(values[key])

    (ROOT / "gtk/hypr-ui.css").write_text(re.sub(r"\{\{([\w.]+)\}\}", sub, tpl))


def qml(tokens, values):
    lines = ["pragma Singleton", "import QtQuick", "import Quickshell", "", f"// {HEADER}", "Singleton {"]
    for k, v in tokens["color"].items():
        lines.append(f'    readonly property color {k}: "{v}"')
    lines.append("")
    for path, v in values.items():
        if path.startswith("color."):
            continue
        name = camel(path)
        if isinstance(v, str):
            lines.append(f"    readonly property string {name}: {json.dumps(v)}")
        elif isinstance(v, float):
            lines.append(f"    readonly property real {name}: {v}")
        else:
            lines.append(f"    readonly property int {name}: {v}")
    lines += ["", "    function alpha(c, a) { return Qt.rgba(c.r, c.g, c.b, a); }", "}", ""]
    (ROOT / "qml").mkdir(exist_ok=True)
    (ROOT / "qml/Tokens.qml").write_text("\n".join(lines))


def main():
    tokens = json.loads((ROOT / "tokens.json").read_text())
    values = flat(tokens)
    gtk(tokens, values)
    qml(tokens, values)
    print("wrote gtk/hypr-ui.css, qml/Tokens.qml")


if __name__ == "__main__":
    main()
